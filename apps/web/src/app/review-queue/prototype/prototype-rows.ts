function row(
  id: number,
  minute: number,
  fields: Partial<Row> & Pick<Row, 'bookingType' | 'code'>,
): Row {
  const time = `2026-11-16T18:${String(minute).padStart(2, '0')}:00Z`;
  return { ...BLANK, id, scannedAt: time, ...fields };
}

